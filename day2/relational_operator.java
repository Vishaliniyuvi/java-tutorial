package day2;

import java.util.Scanner;

public class relational_operator {
    public static void main(String[] args){
        Scanner sha=new Scanner(System.in);
        int a=sha.nextInt();
        int b=sha.nextInt();
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a>=b);
        System.out.println(a<=b);
    }
}
